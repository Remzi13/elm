#include "script/lua/ApiRegistry.hpp"

#include <algorithm>

namespace elm::script::lua {

    namespace {

        String TypeOf(TypeNameFn type)
        {
            return type ? type() : String("any");
        }

        void AppendSignature(String& out, const ApiFunction& function)
        {
            for (const auto& param : function.params)
                out += "---@param " + param.name + " " + TypeOf(param.type) + "\n";
            if (function.variadic)
                out += "---@param ... any\n";
            for (const auto result : function.results)
                out += "---@return " + TypeOf(result) + "\n";
        }

        String ParameterList(const ApiFunction& function)
        {
            String list;
            for (const auto& param : function.params) {
                if (!list.empty())
                    list += ", ";
                list += param.name;
            }
            if (function.variadic)
                list += list.empty() ? "..." : ", ...";
            return list;
        }

        /// "a.b.c" -> "a", "a.b", "a.b.c": every table on the way has to be declared.
        void AddModulePrefixes(Vector<String>& declared, StringView path)
        {
            for (size_t dot = path.find('.'); ; dot = path.find('.', dot + 1)) {
                const String prefix(path.substr(0, dot));
                if (std::find(declared.begin(), declared.end(), prefix) == declared.end())
                    declared.push_back(prefix);
                if (dot == StringView::npos)
                    break;
            }
        }

    } // namespace

    size_t ApiRegistry::AddModule(StringView path)
    {
        const auto it = std::find_if(m_modules.begin(), m_modules.end(),
            [&](const ApiModule& module) { return module.path == path; });
        if (it != m_modules.end())
            return static_cast<size_t>(it - m_modules.begin());
        m_modules.emplace_back().path = String(path);
        return m_modules.size() - 1;
    }

    size_t ApiRegistry::AddClass(StringView name, StringView module)
    {
        auto& added = m_classes.emplace_back();
        added.name = String(name);
        added.module = String(module);
        return m_classes.size() - 1;
    }

    String ApiRegistry::GenerateLuaMeta() const
    {
        String out = "---@meta\n-- Generated by the engine (--dump-script-api), do not edit.\n\n";

        Vector<String> tables;
        for (const auto& module : m_modules)
            AddModulePrefixes(tables, module.path);
        for (const auto& added : m_classes)
            AddModulePrefixes(tables, added.module);
        for (const auto& table : tables) {
            out += "---@class " + table + "\n";
            out += table + " = {}\n\n";
        }

        for (const auto& module : m_modules) {
            for (const auto& value : module.values)
                out += "---@type " + TypeOf(value.type) + "\n" + module.path + "." + value.name + " = nil\n\n";
            for (const auto& function : module.functions) {
                AppendSignature(out, function);
                out += "function " + module.path + "." + function.name + "(" + ParameterList(function) + ") end\n\n";
            }
        }

        for (const auto& added : m_classes) {
            out += "---@class " + added.name + "\n";
            for (const auto& field : added.fields)
                out += "---@field " + field.name + " " + TypeOf(field.type) + (field.readOnly ? " (read only)" : "") + "\n";
            for (const auto& function : added.functions) {
                if (function.kind != ApiFunction::Kind::Constructor)
                    continue;
                out += "---@overload fun(";
                for (size_t index = 0; index < function.params.size(); ++index)
                    out += (index ? ", " : "") + function.params[index].name + ": " + TypeOf(function.params[index].type);
                out += "): " + added.name + "\n";
            }
            out += "local " + added.name + " = {}\n";
            out += added.module + "." + added.name + " = " + added.name + "\n\n";

            for (const auto& function : added.functions) {
                AppendSignature(out, function);
                const char* separator = function.kind == ApiFunction::Kind::Method ? ":" : ".";
                const String name = function.kind == ApiFunction::Kind::Constructor ? String("new") : function.name;
                out += "function " + added.name + separator + name + "(" + ParameterList(function) + ") end\n\n";
            }
        }
        return out;
    }

} // namespace elm::script::lua
